import { readFileSync, writeFileSync } from "node:fs";
import { BLOCK_READINESS_LABEL, blockReadiness, type CourseState, methodCoverage, type ShelfEntry } from "@corniversity/core";
import type { ContentBundle } from "./schema";

/**
 * The per-block, per-elective, per-method and per-source tables of docs/MIND_BRAIN_AI.md,
 * generated from the catalogue so they cannot drift from it. Readiness is derived exactly as the
 * application derives it, and a source counts as verified only when it has a record with what
 * was inspected; a name on a shelf without a record is a lead.
 */

export const COVERAGE_START = "<!-- coverage:start (generated by `pnpm content:coverage`; do not edit by hand) -->";
export const COVERAGE_END = "<!-- coverage:end -->";

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"}`;

export function courseStates(bundle: ContentBundle): Map<string, CourseState> {
  return new Map(
    bundle.courses.map((c) => [
      c.spec.id,
      {
        courseId: c.spec.id,
        title: c.spec.title,
        readiness: c.spec.readiness,
        units: c.units.map((u) => ({ id: u.spec.id, sequence: u.spec.sequence, title: u.spec.title, status: u.spec.status })),
      },
    ]),
  );
}

function describeShelf(shelf: readonly ShelfEntry[]): string {
  const spine = shelf.filter((e) => e.role === "spine").map((e) => (e.sourceId ? `\`${e.sourceId}\`` : `lead "${e.candidate}"`));
  const otherRecords = shelf.filter((e) => e.role !== "spine" && e.sourceId).length;
  const leads = shelf.filter((e) => e.candidate).length;
  return [
    spine.length ? `spine ${spine.join(", ")}` : "no spine",
    otherRecords ? `${plural(otherRecords, "more verified record")}` : null,
    leads ? `${plural(leads, "lead")}, not verified` : "no leads",
  ]
    .filter(Boolean)
    .join("; ");
}

export function coverageTables(bundle: ContentBundle, programmeId: string): string {
  const programme = bundle.programmes.find((p) => p.id === programmeId);
  if (!programme) throw new Error(`programme ${programmeId} is not in the catalogue`);
  const courses = courseStates(bundle);
  const units = new Map(bundle.courses.flatMap((c) => c.units.map((u) => [u.spec.id, u] as const)));
  const courseSpecs = new Map(bundle.courses.map((c) => [c.spec.id, c.spec]));
  const status = (unitId: string) => units.get(unitId)?.spec.status ?? "missing";
  const checks = (unitId: string) => {
    const recorded = units.get(unitId)?.spec.checks ?? [];
    const passed = recorded.filter((c) => c.result === "pass").length;
    return recorded.length ? `${unitId} recorded checks ${passed} of ${recorded.length} pass` : `${unitId} has no recorded checks`;
  };
  const locators = (unitId: string) => {
    const spec = units.get(unitId)?.spec;
    if (!spec) return 0;
    return new Set([...spec.activities.flatMap((a) => a.sourceLocatorIds), ...spec.preparation.map((p) => p.locatorId)]).size;
  };
  const blocks = programme.blocks ?? [];
  const out: string[] = [];

  out.push(
    "### Blocks",
    "",
    `Location is the block's page; the block itself lives in \`content/programmes/${programme.id}.json\`.`,
    "",
    "| Block | Location | Courses and units | Sources and locators | Readiness (derived) | Remaining gap | Evidence |",
    "|---|---|---|---|---|---|---|",
  );
  for (const block of blocks) {
    const report = blockReadiness(block, courses);
    const mapped = block.courseMappings
      .map((m) =>
        m.unitIds.length === 0
          ? `${m.courseId}: no unit chosen`
          : `${m.courseId}: ${m.unitIds.map((id) => `${id} (${status(id)})`).join(", ")}`,
      )
      .join("; ");
    const located = report.preparedUnitIds.map((id) => `${id} cites ${plural(locators(id), "verified locator")}`);
    const gap = [
      ...block.gaps,
      ...(report.unpreparedUnitIds.length ? [`Not yet prepared: ${report.unpreparedUnitIds.join(", ")}.`] : []),
      ...(report.coursesToRefine.length ? [`Units still to choose in ${report.coursesToRefine.join(", ")}.`] : []),
    ].join(" ");
    const evidence = ["validator (mappings, shelf)", "progress tests (derivation)", ...report.preparedUnitIds.map(checks)].join("; ");
    out.push(
      `| ${block.id} ${cell(block.title)} | \`/programmes/${programme.id}/blocks/${block.id}\` | ${cell(mapped)} | ${cell([describeShelf(block.sourceShelf), ...located].join("; "))} | ${BLOCK_READINESS_LABEL[report.readiness]} | ${cell(gap || "None recorded.")} | ${cell(evidence)} |`,
    );
  }

  out.push(
    "",
    "### Electives",
    "",
    "| Elective | Location | Connects to | Readiness | Sources | Remaining gap | Evidence |",
    "|---|---|---|---|---|---|---|",
  );
  for (const elective of programme.electives ?? []) {
    const spec = courseSpecs.get(elective.courseId);
    const course = courses.get(elective.courseId);
    const prepared = course?.units.filter((u) => u.status === "ready").length ?? 0;
    const sources = `${plural(spec?.primarySourceIds.length ?? 0, "verified record")}; ${plural(spec?.sourceCandidates?.length ?? 0, "lead")}`;
    const gap = [prepared ? null : "No prepared unit.", spec?.preparationPath ?? null].filter(Boolean).join(" ");
    out.push(
      `| ${elective.courseId} ${cell(spec?.title ?? "missing")} | \`/courses/${elective.courseId}\` | ${elective.connectsToBlockIds.join(", ")} | ${spec?.readiness ?? "missing"}; offered for ${spec?.modesOffered.join(" and ") ?? "nothing"} | ${sources} | ${cell(gap || "None recorded.")} | validator; seed test (no automatic enrolment) |`,
    );
  }

  out.push(
    "",
    "### Modelling methods",
    "",
    "Location: the programme's `methods`, shown on the programme page and the programme map.",
    "",
    "| Method | Units and roles | Readiness | Remaining gap | Evidence |",
    "|---|---|---|---|---|",
  );
  const coverage = methodCoverage(programme.methods ?? [], courses, new Map());
  for (const method of programme.methods ?? []) {
    const covered = coverage.find((c) => c.methodId === method.id);
    const roles = method.units.map((u) => `${u.unitId} ${u.role} (${status(u.unitId)})`).join("; ");
    const readiness = covered?.plannedOnly ? "planned only" : `carried by ${plural(covered?.preparedUnits.length ?? 0, "prepared unit")}`;
    const gap = [covered?.plannedOnly ? "No prepared unit." : null, ...method.plannedIn.map((p) => `${p.courseId}: ${p.note}`)]
      .filter(Boolean)
      .join(" ");
    const evidence = [
      "validator (each unit teaches the method's concept)",
      "progress tests (the learner's state moves only on evidence)",
      ...(covered?.preparedUnits ?? []).map((u) => checks(u.unitId)),
    ].join("; ");
    out.push(
      `| ${method.section} ${cell(method.title)} | ${cell(roles || "none")} | ${readiness} | ${cell(gap || "None recorded.")} | ${cell(evidence)} |`,
    );
  }

  const shelfUse = new Map<string, string[]>();
  const leads: { name: string; where: string; note: string }[] = [];
  for (const block of blocks) {
    for (const entry of block.sourceShelf) {
      if (entry.sourceId) shelfUse.set(entry.sourceId, [...(shelfUse.get(entry.sourceId) ?? []), `${block.id} ${entry.role}`]);
      else if (entry.candidate) leads.push({ name: entry.candidate, where: `${block.id} shelf`, note: entry.note });
    }
  }
  const programmeCourses = new Set([
    ...blocks.flatMap((b) => b.courseMappings.map((m) => m.courseId)),
    ...(programme.electives ?? []).map((e) => e.courseId),
  ]);
  for (const courseId of [...programmeCourses].sort()) {
    for (const candidate of courseSpecs.get(courseId)?.sourceCandidates ?? []) {
      leads.push({ name: candidate.name, where: courseId, note: candidate.note });
    }
  }
  const sources = new Map(bundle.sources.map((s) => [s.id, s]));
  out.push(
    "",
    "### Sources on the block shelves",
    "",
    `${plural(shelfUse.size, "verified record")} on the shelves and ${plural(leads.length, "lead")} awaiting resolution (below). A record holds what was opened and what was not; a bibliographic entry alone is not a review, and each record's limitations say what was not checked.`,
    "",
    "| Source | Version inspected | Verified | What was seen | Access and processing | Limitations | Shelves |",
    "|---|---|---|---|---|---|---|",
  );
  for (const id of [...shelfUse.keys()].sort()) {
    const record = sources.get(id);
    const version = record?.versions.find((v) => v.id === record.currentVersionId);
    if (!record || !version) {
      out.push(`| \`${id}\` | no record | — | — | — | — | ${shelfUse.get(id)!.join(", ")} |`);
      continue;
    }
    out.push(
      `| \`${id}\` | ${cell(version.label)} | ${version.verifiedAt} by ${cell(version.verifiedBy)} | ${plural(version.componentsSeen.length, "component")} listed in the record | ${version.accessStatus}; ${version.importAllowed ? "import allowed" : "no import"} | ${plural(version.limitations.length, "limitation")} recorded | ${shelfUse.get(id)!.join(", ")} |`,
    );
  }
  out.push("", "### Leads awaiting resolution", "", "| Lead | Named by | Note |", "|---|---|---|");
  for (const lead of leads) out.push(`| ${cell(lead.name)} | ${lead.where} | ${cell(lead.note)} |`);
  if (leads.length === 0) out.push("| none | — | — |");
  return out.join("\n");
}

/** The document with its generated section replaced; throws if the markers are missing. */
export function withCoverage(document: string, tables: string): string {
  const start = document.indexOf(COVERAGE_START);
  const end = document.indexOf(COVERAGE_END);
  if (start < 0 || end < start) throw new Error("the coverage markers are missing from the document");
  return `${document.slice(0, start + COVERAGE_START.length)}\n\n${tables}\n\n${document.slice(end)}`;
}

export function writeCoverage(path: string, bundle: ContentBundle, programmeId: string): void {
  writeFileSync(path, withCoverage(readFileSync(path, "utf8"), coverageTables(bundle, programmeId)));
}
