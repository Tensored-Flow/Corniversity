/**
 * Academic records: an explicitly informal transcript, a portfolio of accepted work and
 * laboratory interpretations, and an end-of-term review derived from recorded evidence by fixed
 * rules. Nothing here is generated by a model, and nothing implies accreditation.
 */

export interface TranscriptCourse {
  courseId: string;
  title: string;
  mode: string;
  status: string;
  enrolledAt: Date;
  completedAt: Date | null;
  version: number;
  readiness: string;
  units: { total: number; prepared: number; withCompletedSessions: number };
  exercises: { total: number; attempted: number; accepted: number; revisionRequested: number };
  concepts: Record<EvidenceState, number>;
  lastActivity: Date | null;
}

const EMPTY_STATES: Record<EvidenceState, number> = { unassessed: 0, introduced: 0, practised: 0, demonstrated: 0, revisit: 0 };

export async function transcript(db: DbOrTx, ownerId: string): Promise<TranscriptCourse[]> {
  const enrolments = await listEnrolments(db, ownerId);
  const out: TranscriptCourse[] = [];
  for (const e of enrolments) {
    const [current] = await db
      .select()
      .from(courseVersion)
      .where(and(eq(courseVersion.courseId, e.course.id), eq(courseVersion.isCurrent, true)))
      .limit(1);
    const version = current ?? e.version;
    const units = await db
      .select({ id: teachingUnit.id, status: teachingUnit.status })
      .from(teachingUnit)
      .where(eq(teachingUnit.courseVersionId, version.id));
    const unitIds = units.map((u) => u.id);
    const sessions = unitIds.length
      ? await db
          .select({ unitId: learningSession.unitId, status: learningSession.status, lastActiveAt: learningSession.lastActiveAt })
          .from(learningSession)
          .where(and(eq(learningSession.ownerId, ownerId), eq(learningSession.enrolmentId, e.enrolment.id)))
      : [];
    const exercises = unitIds.length
      ? await db.select({ id: unitExercise.id }).from(unitExercise).where(inArray(unitExercise.unitId, unitIds))
      : [];
    const exerciseIds = exercises.map((x) => x.id);
    const attempts = exerciseIds.length
      ? await db
          .select({ state: attempt.state })
          .from(attempt)
          .where(and(eq(attempt.ownerId, ownerId), inArray(attempt.exerciseId, exerciseIds)))
      : [];
    const taught = version.teachesConceptIds;
    const states = taught.length
      ? await db
          .select()
          .from(conceptState)
          .where(and(eq(conceptState.ownerId, ownerId), inArray(conceptState.conceptId, taught)))
      : [];
    const concepts: Record<EvidenceState, number> = { ...EMPTY_STATES };
    for (const id of taught) concepts[(states.find((s) => s.conceptId === id)?.state ?? "unassessed") as EvidenceState] += 1;
    const lastActivity = sessions.reduce<Date | null>((latest, s) => (!latest || s.lastActiveAt > latest ? s.lastActiveAt : latest), null);
    out.push({
      courseId: e.course.id,
      title: e.course.title,
      mode: e.enrolment.mode,
      status: e.enrolment.status,
      enrolledAt: e.enrolment.enrolledAt,
      completedAt: e.enrolment.completedAt,
      version: version.version,
      readiness: version.readiness,
      units: {
        total: units.length,
        prepared: units.filter((u) => u.status === "ready").length,
        withCompletedSessions: new Set(sessions.filter((s) => s.status === "completed").map((s) => s.unitId)).size,
      },
      exercises: {
        total: exerciseIds.length,
        attempted: attempts.filter((a) => a.state !== "draft").length,
        accepted: attempts.filter((a) => a.state === "accepted").length,
        revisionRequested: attempts.filter((a) => a.state === "revision_requested").length,
      },
      concepts,
      lastActivity,
    });
  }
  return out;
}

export interface PortfolioItem {
  kind: "accepted_submission" | "lab_interpretation" | "artifact";
  title: string;
  courseId: string | null;
  date: Date;
  excerpt: string;
  href: string | null;
}

export async function portfolio(db: DbOrTx, ownerId: string): Promise<PortfolioItem[]> {
  const accepted = await db
    .select({
      exerciseTitle: unitExercise.title,
      exerciseId: unitExercise.id,
      unitId: unitExercise.unitId,
      content: submissionVersion.contentMarkdown,
      completedAt: assessmentRun.completedAt,
      submittedAt: submissionVersion.submittedAt,
      sessionId: attempt.learningSessionId,
      courseVersionId: teachingUnit.courseVersionId,
    })
    .from(assessmentRun)
    .innerJoin(submissionVersion, eq(assessmentRun.submissionVersionId, submissionVersion.id))
    .innerJoin(attempt, eq(submissionVersion.attemptId, attempt.id))
    .innerJoin(unitExercise, eq(attempt.exerciseId, unitExercise.id))
    .innerJoin(teachingUnit, eq(unitExercise.unitId, teachingUnit.id))
    .where(and(eq(attempt.ownerId, ownerId), eq(assessmentRun.verdict, "accepted")))
    .orderBy(desc(assessmentRun.completedAt));
  const enrolments = await listEnrolments(db, ownerId);
  const versions = await db.select({ id: courseVersion.id, courseId: courseVersion.courseId }).from(courseVersion);
  const courseOfVersion = new Map(versions.map((v) => [v.id, v.courseId]));
  const items: PortfolioItem[] = accepted.map((a) => ({
    kind: "accepted_submission",
    title: a.exerciseTitle,
    courseId: courseOfVersion.get(a.courseVersionId) ?? null,
    date: a.completedAt ?? a.submittedAt,
    excerpt: a.content.replace(/\s+/g, " ").slice(0, 200),
    href: a.sessionId ? `/sessions/${a.sessionId}?exercise=${a.exerciseId}` : null,
  }));
  const labs = await db
    .select()
    .from(notebookEntry)
    .where(and(eq(notebookEntry.ownerId, ownerId), eq(notebookEntry.kind, "calculation")))
    .orderBy(desc(notebookEntry.createdAt));
  for (const l of labs.filter((l) => l.tags.includes("lab"))) {
    items.push({
      kind: "lab_interpretation",
      title: l.title,
      courseId: l.courseId,
      date: l.createdAt,
      excerpt: l.bodyMarkdown.replace(/\s+/g, " ").slice(0, 200),
      href: `/notebook/${l.id}`,
    });
  }
  const artifacts = await db
    .select()
    .from(portfolioArtifact)
    .where(eq(portfolioArtifact.ownerId, ownerId))
    .orderBy(desc(portfolioArtifact.createdAt));
  for (const a of artifacts)
    items.push({
      kind: "artifact",
      title: a.title,
      courseId: null,
      date: a.createdAt,
      excerpt: a.description.slice(0, 200),
      href: a.links[0]?.href ?? null,
    });
  return items.sort((a, b) => b.date.getTime() - a.date.getTime());
}

export interface CourseReview {
  courseId: string;
  title: string;
  progress: string;
  strengths: string[];
  gaps: string[];
  unfinished: string[];
  recommendation: string;
}

export interface EndOfTermReview {
  generatedAt: Date;
  basis: string;
  courses: CourseReview[];
  openQuestions: number;
  nextTerm: string[];
}

/** Fixed rules over recorded evidence; the basis sentence is shown with the review. */
export async function endOfTermReview(db: DbOrTx, ownerId: string): Promise<EndOfTermReview> {
  const rows = await transcript(db, ownerId);
  const enrolments = await listEnrolments(db, ownerId);
  const currentVersions = enrolments.length
    ? await db
        .select()
        .from(courseVersion)
        .where(and(inArray(courseVersion.courseId, enrolments.map((e) => e.course.id)), eq(courseVersion.isCurrent, true)))
    : [];
  const allConceptIds = [...new Set(currentVersions.flatMap((v) => v.teachesConceptIds))];
  const concepts = allConceptIds.length ? await db.select().from(concept).where(inArray(concept.id, allConceptIds)) : [];
  const states = allConceptIds.length
    ? await db
        .select()
        .from(conceptState)
        .where(and(eq(conceptState.ownerId, ownerId), inArray(conceptState.conceptId, allConceptIds)))
    : [];
  const title = (id: string) => concepts.find((c) => c.id === id)?.title ?? id;
  const openQuestions = (
    await db
      .select({ id: notebookEntry.id })
      .from(notebookEntry)
      .where(and(eq(notebookEntry.ownerId, ownerId), eq(notebookEntry.kind, "question"), eq(notebookEntry.resolved, false)))
  ).length;
  const courses: CourseReview[] = [];
  for (const row of rows) {
    if (row.status === "withdrawn") continue;
    const taught = currentVersions.find((v) => v.courseId === row.courseId)?.teachesConceptIds ?? [];
    const stateOf = (id: string) => (states.find((s) => s.conceptId === id)?.state ?? "unassessed") as EvidenceState;
    const strengths = taught.filter((id) => stateOf(id) === "demonstrated").map(title);
    const gaps = taught.filter((id) => stateOf(id) === "revisit").map(title);
    const unfinished = taught.filter((id) => stateOf(id) === "introduced" || stateOf(id) === "practised").map(title);
    const progress = `${row.units.withCompletedSessions} of ${row.units.prepared} prepared unit(s) worked (${row.units.total} in the syllabus); ${row.exercises.accepted} of ${row.exercises.attempted} attempted exercise(s) accepted.`;
    let recommendation: string;
    if (gaps.length)
      recommendation = `Revisit ${gaps.slice(0, 3).join(", ")} before moving on; the record shows a later gap on material that was once demonstrated.`;
    else if (row.units.prepared > 0 && row.units.withCompletedSessions >= row.units.prepared)
      recommendation =
        "The prepared material is exhausted; the remaining units are outlined and await preparation before they can be taught.";
    else if (row.exercises.attempted === 0) recommendation = "No attempts recorded yet; the review has nothing to judge beyond readings.";
    else if (row.exercises.accepted * 2 >= row.exercises.attempted) recommendation = "Ready to continue with the next prepared unit.";
    else recommendation = "Most attempts still await an accepted revision; finish those before new material.";
    courses.push({ courseId: row.courseId, title: row.title, progress, strengths, gaps, unfinished, recommendation });
  }
  const nextTerm = courses.map((c) => `${c.courseId}: ${c.recommendation}`);
  if (openQuestions) nextTerm.push(`${openQuestions} open question(s) remain on the notebook shelf; carry them forward deliberately.`);
  return {
    generatedAt: new Date(),
    basis:
      "Derived from recorded evidence events, attempt states and completed sessions by fixed rules in the application; no model was consulted and no time-on-task is counted.",
    courses,
    openQuestions,
    nextTerm,
  };
}

export interface RecordsBundle {
  format: "corniversity-records/1";
  generatedAt: string;
  learner: { displayName: string; timezone: string; goals: string | null };
  disclaimer: string;
  transcript: TranscriptCourse[];
  portfolio: PortfolioItem[];
  review: EndOfTermReview;
  concepts: { id: string; title: string; state: string; selfConfidence: number | null }[];
  evidence: { conceptId: string; type: string; observedAt: Date; interpretation: string; reviewStatus: string }[];
  notebook: (typeof notebookEntry.$inferSelect)[];
  annotations: { item: string; locator: unknown; selectedText: string | null; note: string; createdAt: Date; mappingStatus: string }[];
}

export async function buildRecordsBundle(db: DbOrTx, ownerId: string): Promise<RecordsBundle> {
  const [profile] = await db.select().from(learnerProfile).where(eq(learnerProfile.userId, ownerId)).limit(1);
  const [tr, pf, review] = await Promise.all([transcript(db, ownerId), portfolio(db, ownerId), endOfTermReview(db, ownerId)]);
  const states = await db
    .select({ state: conceptState, concept })
    .from(conceptState)
    .innerJoin(concept, eq(concept.id, conceptState.conceptId))
    .where(eq(conceptState.ownerId, ownerId));
  const events = await db
    .select()
    .from(evidenceEvent)
    .where(eq(evidenceEvent.ownerId, ownerId))
    .orderBy(desc(evidenceEvent.observedAt))
    .limit(2000);
  const notes = await db.select().from(notebookEntry).where(eq(notebookEntry.ownerId, ownerId)).orderBy(desc(notebookEntry.updatedAt));
  const annotations = await db
    .select({ annotation, title: resourceAsset.confirmedTitle, filename: resourceAsset.filename })
    .from(annotation)
    .leftJoin(resourceAsset, eq(annotation.assetId, resourceAsset.id))
    .where(eq(annotation.ownerId, ownerId));
  return {
    format: "corniversity-records/1",
    generatedAt: new Date().toISOString(),
    learner: {
      displayName: profile?.displayName ?? "Learner",
      timezone: profile?.timezone ?? "Europe/London",
      goals: profile?.goalsText ?? null,
    },
    disclaimer:
      "Informal personal record from a private, independent, non-accredited personal university. Evidence states are derived from recorded attempts and readings; feedback came from AI personas or deterministic checks and is provisional.",
    transcript: tr,
    portfolio: pf,
    review,
    concepts: states.map((s) => ({
      id: s.concept.id,
      title: s.concept.title,
      state: s.state.state,
      selfConfidence: s.state.selfConfidence,
    })),
    evidence: events.map((e) => ({
      conceptId: e.conceptId,
      type: e.evidenceType,
      observedAt: e.observedAt,
      interpretation: e.interpretation,
      reviewStatus: e.reviewStatus,
    })),
    notebook: notes,
    annotations: annotations.map((a) => ({
      item: a.title ?? a.filename ?? "(deleted item)",
      locator: a.annotation.locator,
      selectedText: a.annotation.selectedText,
      note: a.annotation.noteMarkdown,
      createdAt: a.annotation.createdAt,
      mappingStatus: a.annotation.mappingStatus,
    })),
  };
}

/** Human-readable export in the spirit of ALTER's Markdown notes: one document, plain headings, no claims beyond the record. */
export function renderMarkdownExport(bundle: RecordsBundle): string {
  const lines: string[] = [];
  lines.push(
    `# ${bundle.learner.displayName}: personal academic record (informal)`,
    "",
    `Generated ${bundle.generatedAt.slice(0, 10)}. ${bundle.disclaimer}`,
    "",
  );
  if (bundle.learner.goals) lines.push("## Goals", "", bundle.learner.goals, "");
  lines.push("## Courses", "");
  for (const c of bundle.transcript) {
    lines.push(
      `### ${c.courseId} ${c.title}`,
      "",
      `- Mode: ${c.mode} · status: ${c.status} · enrolled ${c.enrolledAt.toISOString().slice(0, 10)} · course version ${c.version} (${c.readiness})`,
    );
    lines.push(`- Units: ${c.units.withCompletedSessions} of ${c.units.prepared} prepared worked, ${c.units.total} in the syllabus`);
    lines.push(`- Exercises: ${c.exercises.accepted} accepted of ${c.exercises.attempted} attempted (${c.exercises.total} available)`);
    lines.push(
      `- Concepts: ${Object.entries(c.concepts)
        .map(([k, v]) => `${k} ${v}`)
        .join(", ")}`,
      "",
    );
  }
  lines.push("## Portfolio", "");
  if (bundle.portfolio.length === 0) lines.push("Nothing accepted yet.", "");
  for (const p of bundle.portfolio)
    lines.push(
      `- ${p.date.toISOString().slice(0, 10)} · ${p.kind.replace("_", " ")} · **${p.title}**${p.courseId ? ` (${p.courseId})` : ""}: ${p.excerpt}`,
    );
  lines.push("", "## End-of-term review", "", bundle.review.basis, "");
  for (const c of bundle.review.courses) {
    lines.push(`### ${c.courseId} ${c.title}`, "", c.progress, "");
    if (c.strengths.length) lines.push(`- Demonstrated: ${c.strengths.join(", ")}`);
    if (c.gaps.length) lines.push(`- To revisit: ${c.gaps.join(", ")}`);
    if (c.unfinished.length) lines.push(`- Met but not yet demonstrated: ${c.unfinished.join(", ")}`);
    lines.push(`- Recommendation: ${c.recommendation}`, "");
  }
  lines.push("## Notebook", "");
  for (const n of bundle.notebook) {
    lines.push(
      `### ${n.title}`,
      "",
      `*${n.kind}${n.courseId ? ` · ${n.courseId}` : ""}${n.tags.length ? ` · ${n.tags.join(", ")}` : ""} · ${n.updatedAt.toISOString().slice(0, 10)}*`,
      "",
      n.bodyMarkdown,
      "",
    );
    if (n.sourceLinks.length) lines.push(`Sources: ${n.sourceLinks.map((l) => l.label).join("; ")}`, "");
  }
  if (bundle.annotations.length) {
    lines.push("## Reading notes", "");
    for (const a of bundle.annotations)
      lines.push(
        `- ${a.createdAt.toISOString().slice(0, 10)} · ${a.item}${a.mappingStatus === "needs_repair" ? " (anchor needs repair)" : ""}: ${a.note}${a.selectedText ? ` — on: "${a.selectedText.slice(0, 160)}"` : ""}`,
      );
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

export type ExportKind = "full" | "notebook" | "records" | "alter_markdown";

export async function requestExport(db: DbOrTx, ownerId: string, kind: ExportKind): Promise<{ exportId: string }> {
  const [row] = await db.insert(exportRecord).values({ ownerId, kind, status: "queued" }).returning({ id: exportRecord.id });
  const payload = ExportRecordsPayload.parse({ idempotencyKey: `export:${row!.id}`, ownerId, exportId: row!.id, kind });
  await enqueue(db, { queue: QUEUES.exportRecords, kind: "export-records", payload });
  return { exportId: row!.id };
}

export async function listExports(db: DbOrTx, ownerId: string) {
  return db.select().from(exportRecord).where(eq(exportRecord.ownerId, ownerId)).orderBy(desc(exportRecord.createdAt)).limit(20);
}

export async function getExport(db: DbOrTx, ownerId: string, id: string) {
  const rows = await db
    .select()
    .from(exportRecord)
    .where(and(eq(exportRecord.id, id), eq(exportRecord.ownerId, ownerId)))
    .limit(1);
  return rows[0] ?? null;
}
